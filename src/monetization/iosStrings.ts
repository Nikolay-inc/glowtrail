// Переводы текстов Info.plist (iOS) из i18n — для scripts/ios-strings.ts и теста. Без Phaser и без SDK.

import en from '../i18n/en.json';
import ru from '../i18n/ru.json';
import uk from '../i18n/uk.json';
import { ATT_TEXT_KEY } from './config';

export const IOS_LANGS = ['en', 'ru', 'uk'] as const;
const TABLES: Record<(typeof IOS_LANGS)[number], Record<string, string>> = { en, ru, uk };

const esc = (s: string) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

/** Содержимое <язык>.lproj/InfoPlist.strings. */
export function infoPlistStrings(lang: (typeof IOS_LANGS)[number]): string {
  return `/* Generated by npm run ios:strings from src/i18n/${lang}.json — do not edit by hand. */\n"NSUserTrackingUsageDescription" = "${esc(TABLES[lang][ATT_TEXT_KEY])}";\n`;
}
